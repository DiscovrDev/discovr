/**
 * Injects the compiled sample files under `public/samples/` into the guide MDX
 * (see `guide-samples/lib.ts` for the marker syntax).
 *
 *   tsx public/scripts/inject-guide-samples.ts           rewrite the guides
 *   tsx public/scripts/inject-guide-samples.ts --check   fail if any guide is stale
 *
 * TypeScript fences are formatted with the repo's Prettier config here, so
 * `docs:format` finds nothing left to change and `--check` stays stable.
 */

import * as fs from "node:fs";
import * as path from "node:path";
import { fileURLToPath } from "node:url";

import * as prettier from "prettier";

import {
	findSampleIds,
	injectSamples,
	loadSampleFile,
	type FormatCode,
	type Language,
} from "./guide-samples/lib";

const SCRIPT_DIR = path.dirname(fileURLToPath(import.meta.url));
const ROOT = path.resolve(SCRIPT_DIR, "../..");
const SAMPLES_ROOT = path.join(ROOT, "public/samples");
const GUIDES_DIR = path.join(ROOT, "public/docs/guides");
// Generated by `sdk:docs`, which leaves the install block empty for this script to fill,
// so the install snippet has one source for the guides and the reference.
const EXTRA_FILES = [path.join(ROOT, "public/docs/sdk-reference/index.mdx")];

const CHECK = process.argv.includes("--check");

function mdxFiles(dir: string): string[] {
	return fs
		.readdirSync(dir, { withFileTypes: true })
		.flatMap((entry) => {
			const full = path.join(dir, entry.name);
			if (entry.isDirectory()) return mdxFiles(full);
			return entry.name.endsWith(".mdx") ? [full] : [];
		})
		.sort();
}

async function main(): Promise<void> {
	const prettierOptions = (await prettier.resolveConfig(path.join(ROOT, "x.ts"))) ?? {};

	const stale: string[] = [];
	let injected = 0;

	for (const file of [...mdxFiles(GUIDES_DIR), ...EXTRA_FILES.filter((f) => fs.existsSync(f))]) {
		const original = fs.readFileSync(file, "utf8");
		const ids = findSampleIds(original);
		if (ids.length === 0) continue;

		// Prettier is async, `injectSamples` is not: format each TS sample up front.
		const formatted = new Map<string, string>();
		for (const id of new Set(ids)) {
			const ts = loadSampleFile(SAMPLES_ROOT, id, "typescript");
			if (ts.fence !== "typescript") continue;
			formatted.set(
				id,
				await prettier.format(ts.code, { ...prettierOptions, parser: "typescript" }),
			);
		}

		const rel = path.relative(ROOT, file);
		// `injectSamples` hands the formatter only the code; find the id by its source text.
		const byCode = new Map<string, string>();
		for (const id of formatted.keys()) {
			byCode.set(loadSampleFile(SAMPLES_ROOT, id, "typescript").code, formatted.get(id)!);
		}
		const format: FormatCode = (code: string, language: Language) =>
			language === "typescript" ? (byCode.get(code) ?? code) : code;

		const { mdx } = injectSamples(original, SAMPLES_ROOT, format, rel);
		injected += ids.length;

		if (mdx !== original) {
			if (CHECK) stale.push(rel);
			else fs.writeFileSync(file, mdx);
		}
	}

	if (CHECK && stale.length > 0) {
		console.error(
			`These guides are out of date with public/samples/. Run \`npm run inject:guide:samples\`:\n${stale
				.map((f) => `  ${f}`)
				.join("\n")}`,
		);
		process.exit(1);
	}
	console.log(`${CHECK ? "Checked" : "Injected"} ${injected} guide code samples.`);
}

main().catch((err) => {
	console.error(err instanceof Error ? err.message : err);
	process.exit(1);
});
